// ===== Real-time professional experience clock =====
const EXPERIENCE_START = new Date('2026-02-02T00:00:00');
const experienceClock = document.getElementById('experience-clock');

function getElapsed(start, now) {
  let years = now.getFullYear() - start.getFullYear();
  let months = now.getMonth() - start.getMonth();
  let days = now.getDate() - start.getDate();
  let hours = now.getHours() - start.getHours();
  let minutes = now.getMinutes() - start.getMinutes();
  let seconds = now.getSeconds() - start.getSeconds();

  if (seconds < 0) { seconds += 60; minutes--; }
  if (minutes < 0) { minutes += 60; hours--; }
  if (hours < 0) { hours += 24; days--; }
  if (days < 0) {
    const prevMonth = new Date(now.getFullYear(), now.getMonth(), 0);
    days += prevMonth.getDate();
    months--;
  }
  if (months < 0) { months += 12; years--; }

  return { years, months, days, hours, minutes, seconds };
}

function pad(n) {
  return String(n).padStart(2, '0');
}

function renderExperienceClock() {
  const now = new Date();
  if (now < EXPERIENCE_START) {
    experienceClock.textContent = t(currentLang, 'clock.comingSoon');
    return;
  }

  const { years, months, days, hours, minutes, seconds } = getElapsed(EXPERIENCE_START, now);
  const parts = [];
  if (years > 0) parts.push(`${years} ${years === 1 ? t(currentLang, 'clock.year') : t(currentLang, 'clock.years')}`);
  parts.push(`${months} ${months === 1 ? t(currentLang, 'clock.month') : t(currentLang, 'clock.months')}`);
  parts.push(`${days} ${days === 1 ? t(currentLang, 'clock.day') : t(currentLang, 'clock.days')}`);

  experienceClock.textContent = `${parts.join(', ')} · ${pad(hours)}:${pad(minutes)}:${pad(seconds)}`;
}

setInterval(renderExperienceClock, 1000);

